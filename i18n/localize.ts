import type { Lang } from "./dictionary";

/*
 * Mandir ka naam, shehar, rajya, devta, puja ke naam aur timings
 * Hindi / Bengali / Urdu me badalne ke liye.
 * Format har line me:  English | हिन्दी | বাংলা | اردو
 */

type Row = [string, string, string];
const IDX: Record<Exclude<Lang, "en">, 0 | 1 | 2> = { hi: 0, bn: 1, ur: 2 };

function parse(blob: string): Record<string, Row> {
    const out: Record<string, Row> = {};
    blob
        .trim()
        .split("\n")
        .forEach((line) => {
            const p = line.split("|").map((s) => s.trim());
            if (p.length === 4) out[p[0]] = [p[1], p[2], p[3]];
        });
    return out;
}

function pick(map: Record<string, Row>, key: string, lang: Lang): string {
    if (lang === "en") return key;
    return map[key]?.[IDX[lang]] ?? key;
}

